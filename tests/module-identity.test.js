"use strict";
const assert = require("node:assert/strict");
const { parse } = require("es-module-lexer/js");
const { rewriteJsText, rewriteHtml } = require("../src/server");
const base = "https://example.com/app/main.js", sid = "test-session";
const extract = s => parse(s)[0].filter(i => i.specifier).map(i => i.specifier);
const a = rewriteJsText('import{x}from"./shared.js";', base, sid);
const b = rewriteJsText('export{x}from"../shared.js";', "https://example.com/app/nested/other.js", sid);
assert.equal(extract(a)[0], extract(b)[0], "Different importing parents must identify the same canonical module");
assert.ok(extract(a)[0].startsWith("/api/resource?"));
assert.equal(new URL(extract(a)[0], "https://proxy.invalid").searchParams.get("sid"), sid);
const dynamic = rewriteJsText('const x=import("./shared.js", {with:{type:"json"}});', base, sid);
assert.equal(extract(dynamic)[0], extract(a)[0]);
assert.ok(dynamic.includes('{with:{type:"json"}}'));
const data = 'const text = `import("./shared.js")`; /* import("./another.js") */';
assert.equal(rewriteJsText(data, base, sid), data);
assert.equal(rewriteJsText('import{html}from"lit";', base, sid), 'import{html}from"lit";');
const html = rewriteHtml('<html><head><link rel="modulepreload" href="./app/shared.js"></head><body><script type="module" src="./app/shared.js"></script></body></html>', "https://example.com/", sid);
const cheerio = require("cheerio"), $ = cheerio.load(html);
assert.equal($('link[rel="modulepreload"]').attr('href'), extract(a)[0]);
assert.equal($('script[type="module"]').attr('src'), extract(a)[0]);
console.log("Module identity: 9 syntax, identity and preload checks passed.");
